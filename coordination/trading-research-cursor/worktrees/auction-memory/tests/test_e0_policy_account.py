    def test_INT08_F03_accounting_denominator_and_cash(self):
        case = E0_INTEGRATION_CASE_MAP["E0-INT-08-F03"]
        with tempfile.TemporaryDirectory() as directory:
            _, accounting = ledgers(Path(directory), eligible_dates=("2024-06-03", "2024-06-04", "2024-06-05", "2024-06-06"))
            entry = TradingFill("exec-entry-a", "1002", "2024-06-03", DECISION, 1, 72000,
                                Decimal("5.03"), fees().version, "fixture-source-v1")
            exit = TradingFill("exec-exit-a", "1002", "2024-06-03", DECISION + 1, -1, 72010,
                               Decimal("5.03"), fees().version, "fixture-source-v1")
            accounting.fill(entry)
            accounting.fill(exit)
            for offset, day, status in ((0, "2024-06-03", "complete"), (1, "2024-06-04", "flat"),
                                        (2, "2024-06-05", "outage"), (3, "2024-06-06", "halted")):
                accounting.day_status(trading_date=day, at=DECISION + offset + 2,
                                      status=status, evidence_version="fixture-accounting-v1")
            accounting.cash(id="purchase-1", at=DECISION, kind="account_purchase",
                            amount=Decimal("100.00"), evidence_version="fixture-accounting-v1")
            report = accounting.report()
            self.assertEqual(report["eligible_day_count"], case["expected"]["eligible_day_count"])
            self.assertEqual(report["trading_net"], Decimal(case["expected"]["trading_net_total_usd"]))
            self.assertEqual(report["mean_net_per_eligible_day"], Fraction(1997, 200))
            self.assertEqual(report["business_net_cash"], Decimal(case["expected"]["business_net_cash_usd"]))
            self.assertTrue(all(report["days"][day]["status"] in {"flat", "outage", "halted", "complete"}
                                for day in ("2024-06-03", "2024-06-04", "2024-06-05", "2024-06-06")))
            with self.assertRaises(IntegrityError):
                accounting.fill(replace(entry, price_ticks=72001))
            with self.assertRaises(IntegrityError):
                accounting.day_status(trading_date="2024-06-03", at=DECISION + 99,
                                      status="flat", evidence_version="conflicting-day-proof")
            self.assertTrue(case["expected"]["flat_outage_halted_in_denominator"])
            self.assertTrue(case["expected"]["duplicate_changed_execution_rejected"])


