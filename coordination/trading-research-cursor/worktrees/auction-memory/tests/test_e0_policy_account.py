    def test_INT08_F02_uncertain_and_gap_variants(self):
        case = E0_INTEGRATION_CASE_MAP["E0-INT-08-F02"]
        plan = replay_plan()
        timing = replay_timing()
        # Missing coverage at the actual entry arrival produces an uncertain
        # venue Fill, which is reported but never appended economically.
        unknown_path = replay_path(coverage_intervals=((DECISION - 100_000_000, REPLAY_ENTRY_AT),))
        unknown_scenario = replay_scenario(coverage_version=unknown_path.coverage_version)
        unknown = replay_outcome(path=unknown_path, plan=plan, timing=timing, scenario=unknown_scenario)
