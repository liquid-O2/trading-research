    def test_INT06_F01_complete_policy_decision(self):
        case = E0_INTEGRATION_CASE_MAP["E0-INT-06-F01"]
        values = {
            "cand-a-long": (value("cand-a-long", 1, bracket_policy(1).target_policy),
                            value("cand-a-long", 1, bracket_policy(2).target_policy)),
            "cand-b-short": (value("cand-b-short", -1, bracket_policy(1).target_policy,
                                   positive=False),),
            "background-0932": (value("background-0932", 1, bracket_policy(1).target_policy,
                                       positive=False),),
        }
        artifacts = (
            E0SyntheticNumericalEvidence("freq-2023-v1", 1704081600000000000,
                                         "reach-depart-15m-v1", "fit-2023-v1", "features-e0-v1",
                                         model_version="freq-2023-v1"),
            E0SyntheticNumericalEvidence("logit-2023-lambda-1-v1", 1704081600000000000,
                                         "reach-depart-15m-v1", "fit-2023-v1", "features-e0-v1",
                                         model_version="logit-2023-lambda-1-v1"),
            E0SyntheticNumericalEvidence("cal-2024-v1", 1704081600000000000,
                                         "reach-depart-15m-v1", "fit-2023-v1", "features-e0-v1",
                                         model_version="cal-2024-v1", calibrator_version="cal-2024-v1"),
        )
