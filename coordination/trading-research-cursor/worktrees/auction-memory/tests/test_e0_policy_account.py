            restarted = E0OutcomeReplay.restore(checkpoint, outcome=outcome, order_ledger=orders,
                                                accounting=accounting, scenario_manifest=manifest,
                                                timing=timing, venue_path=path, fill_scenario=scenario)
            cancel_sent = next(event["at"] for event in outcome.events if event["kind"] == "stop_cancel_sent")
            before_exit = restarted.advance(cancel_sent)
