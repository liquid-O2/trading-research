            self.assertEqual(orders.state()["positions"], {"1002": 1})
            receipt = restarted.advance(restarted.final_cut)
            state = orders.state()
            self.assertFalse(restarted.risk_held)
            self.assertFalse(any(state["positions"].values()))
            self.assertEqual(len(receipt.order_submission_ids), case["expected"]["order_submissions"])
            self.assertEqual(len(receipt.execution_ids), case["expected"]["order_execution_events"])
            self.assertEqual(receipt.execution_ids, tuple(case["expected"]["execution_ids"]))
