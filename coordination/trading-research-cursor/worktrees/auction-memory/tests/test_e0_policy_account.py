    def test_INT06_F03_artifact_abstention_variants(self):
        case = E0_INTEGRATION_CASE_MAP["E0-INT-06-F03"]
        for variant, reason, selected_action in case["variants"]:
            if variant == "future-model":
                value_row = value("cand-a", 1, bracket_policy(1).target_policy,
                                  decision_at=1717421700000000000, known_at=1717421700000000000,
                                  decision_set_id="ds-0935", horizon_end=1717422600000000000)
                artifact = E0SyntheticNumericalEvidence("logit-2024", 1717516800000000000,
                    "reach-depart-15m-v1", "fit-2023-v1", "features-e0-v1",
                    model_version="logit-2024")
            elif variant == "wrong-horizon":
                value_row = value("cand-a", 1, bracket_policy(1).target_policy,
                                  decision_at=1717421700000000000, known_at=1717421700000000000,
                                  decision_set_id="ds-0935", horizon_end=1717422600000000000)
                artifact = E0SyntheticNumericalEvidence("logit-2023-lambda-1-v1", 1704081600000000000,
                    "reach-30m-v1", "fit-2023-v1", "features-e0-v1",
                    model_version="logit-2023-lambda-1-v1")
            else:
                value_row = value("cand-a", 1, bracket_policy(1).target_policy, complete=False,
                                  decision_at=1717421700000000000, known_at=1717421700000000000,
                                  decision_set_id="ds-0935", horizon_end=1717422600000000000)
                artifact = None
            _, decision = score_and_decide_e0(
                decision_set=decision_set("cand-a", id="ds-0935", at=1717421700000000000),
                bracket_candidates={"cand-a": (value_row,)},
                model_artifacts=() if artifact is None else (artifact,))
            self.assertEqual(decision.selected_action, selected_action, variant)
            self.assertEqual(decision.rejected_reasons, (("cand-a", reason),), variant)
            self.assertEqual(decision.risk_verdict, "abstain:" + reason, variant)
        # A complete positive row with its typed lineage deliberately removed
        # cannot become a learned admission merely because its value fields
        # carry model/fold/calibrator strings.
        unbound = replace(value("cand-a", 1, bracket_policy(1).target_policy,
                               decision_set_id="ds-unbound"), artifact_evidence=None)
        _, unbound_decision = score_and_decide_e0(
            decision_set=decision_set("cand-a", id="ds-unbound"),
            bracket_candidates={"cand-a": (unbound,)})
        self.assertEqual(unbound_decision.selected_action, "abstain")
        self.assertEqual(unbound_decision.rejected_reasons,
                         (("cand-a", "model artifact evidence unavailable at decision cut"),))

