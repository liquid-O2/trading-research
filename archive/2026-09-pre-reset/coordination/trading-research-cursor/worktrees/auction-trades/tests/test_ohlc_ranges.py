    def test_jo13_contact_bar_excursions_are_bounds_with_side_mirror(self):
        first = full_window(((98, 110, 90, 100),))
        later = full_window(((98, 110, 90, 100), (100, 106, 99, 104)))
        names = ("favorable_lower_ticks", "favorable_upper_ticks", "adverse_lower_ticks", "adverse_upper_ticks")
        one = level_outcome(first, level=Fraction(100), side=1)
        long = level_outcome(later, level=Fraction(100), side=1)
        short = level_outcome(later, level=Fraction(100), side=-1)
        self.assertEqual(tuple(one[n] for n in names), (0, 10, 0, 10))
        self.assertEqual(tuple(long[n] for n in names), (6, 10, 1, 10))
        self.assertEqual(tuple(short[n] for n in names), (1, 10, 6, 10))
        self.assertEqual((long["status"], long["conditional_on_contact"], long["terminal_from_level_ticks"]),
                         ("definite_level_print", False, 4))
        self.assertEqual(short["terminal_from_level_ticks"], -4)
        self.assertEqual((long["contact_interval_start_ns"], long["contact_interval_end_ns"]), (0, M))

