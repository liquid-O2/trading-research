    def test_jo03_missing_first_middle_last_and_invalid_minutes(self):
        expected = (([1, 2], "missing_first_minute"),
                    ([0, 2], "missing_interior_minutes"),
                    ([0, 1], "missing_last_minute"))
        for indices, reason in expected:
            with self.subTest(reason=reason):
                s = series(tuple((i, (100, 101, 99, 100)) for i in indices))
                window = s.window(0, 3 * M, contract_key=RAW)
                self.assertFalse(window.complete)
                self.assertIn(reason, window.reasons)
                self.assertEqual(window.summary()["status"], "unavailable")
                with self.assertRaises(DependencyUnavailable):
                    window.geometry()
                self.assertEqual(range_path(window, low=96, high=104)["status"], "censored")
                self.assertEqual(level_outcome(window, level=Fraction(100), side=1)["status"], "censored")
        invalid = series(((0, (100, 101, 99, 100)), (1, (100, 101, 99, 100), 2 * M, RAW, False)))
        self.assertIn("invalid_source_minutes", invalid.window(0, 2 * M).reasons)
        self.assertIn("missing_all_minutes", invalid.window(3 * M, 4 * M).reasons)
        import pyarrow as pa
        nullable = columns(((0, (100, 101, 99, 100)),
                            (1, (None, None, None, None), 2 * M, None, False),
                            (2, (102, 103, 101, 102))))
        nullable["volume"][1] = None
        table = pa.table(nullable)
        retained = MinuteBars.from_table(table, source_version="nullable-invalid-minute")
        unavailable = retained.window(0, 3 * M)
        self.assertEqual(unavailable.count, 3)
        self.assertIn("invalid_source_minutes", unavailable.reasons)
        with self.assertRaises(DependencyUnavailable):
            unavailable.geometry()
        self.assertEqual(level_outcome(unavailable, level=Fraction(100), side=1)["status"], "censored")
        self.assertEqual(table["open_ticks"].to_pylist(), [100, None, 102])
        self.assertEqual(retained.window(2 * M, 3 * M).geometry().low, 101)
        nullable["valid"][1] = True
        with self.assertRaises(ContractError):
            MinuteBars.from_table(pa.table(nullable), source_version="valid-null-is-forbidden")
        nullable["valid"][1] = False
        nullable["start_ns"][1] += 1
        nullable["end_ns"][1] += 1
        nullable["known_at_ns"][1] += 1
        offgrid = MinuteBars.from_table(pa.table(nullable), source_version="retained-offgrid-invalid-minute")
        self.assertEqual(offgrid.window(0, 3 * M).count, 3)
        self.assertIn("invalid_source_minutes", offgrid.window(0, 3 * M).reasons)
        self.assertTrue(offgrid.window(2 * M, 3 * M).complete)

