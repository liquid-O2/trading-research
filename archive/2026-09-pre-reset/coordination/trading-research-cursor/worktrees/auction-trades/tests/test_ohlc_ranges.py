    def test_jo15_actual_label_ledger_distinguishes_empty_flat_and_carry(self):
        caps = frozenset({Capability.TERMINAL_RETURN, Capability.EXCURSIONS, Capability.FIRST_PASSAGE})
        variants = (("actual_ohlc_price_observations", (), (), "censored", None),
                    ("actual_ohlc_price_observations", ((M, 100, M + 1),), (), "complete", 0),
                    ("certified_last_observed_mark", (), (), "complete", 0),
                    ("certified_last_observed_mark", (), ((0, M),), "censored", None))
        for process, values, gaps, expected_state, terminal in variants:
            with self.subTest(process=process, values=values, gaps=gaps):
                definition = LabelDefinition("actual-price-definition", "price_path", 0, M, process,
                    favorable_distance=Fraction(3), adverse_distance=Fraction(2), endpoint_group="minute")
                ledger = LabelLedger()
                ledger.add_definition(definition)
                ledger.add_candidate(CandidateRecord("candidate", "birth", "decision-set", "object",
                    "2024-06-03", "episode", SamplingFrame.CLOCK, 0, 0, "untraded",
                    endpoint_group="minute", definition_id=definition.id))
                target = Target("actual-price-target", definition.id, RAW, 0, M, process,
                                "clock", Unit.TICKS, caps)
                points = tuple(PathPoint(at, i, Ticks(price), known)
                               for i, (at, price, known) in enumerate(values))
                outcome = append_price_outcome(ledger, "candidate", definition.id, target=target,
                    initial=Ticks(100), points=points,
                    coverage=ObservationEvidence(M, M + 1, "actual-observation-v1", gaps=gaps),
                    up_ticks=3, down_ticks=2, outcome_id="outcome")
                payload = json.loads(outcome.payload)
                self.assertEqual(outcome.state, expected_state)
                self.assertEqual(payload["data"]["terminal_ticks"], terminal)
                self.assertEqual(payload["data"]["maximum_up_ticks"], terminal)
                self.assertEqual(payload["data"]["maximum_down_ticks"], terminal)
                self.assertEqual(payload["data"]["first_barrier"], "neither" if terminal == 0 else None)
                checkpoint = ledger.checkpoint()
                self.assertEqual(LabelLedger.restore(checkpoint).checkpoint(), checkpoint)
                incompatible = Target("wrong-observation-process", definition.id, RAW, 0, M,
                                      "different_process", "clock", Unit.TICKS, caps)
                with self.assertRaises(ContractError):
                    append_price_outcome(ledger, "candidate", definition.id, target=incompatible,
                        initial=Ticks(100), points=points,
                        coverage=ObservationEvidence(M, M + 1, "actual-observation-v1", gaps=gaps),
                        up_ticks=3, down_ticks=2, outcome_id="wrong-process", supersedes="outcome")
                self.assertEqual(ledger.checkpoint(), checkpoint)

    def test_jo16_dst_short_cash_day_and_overnight_offsets(self):
        expected = ((date(2024, 3, 8), ("2024-03-08T11:00:00+00:00", "2024-03-08T14:00:00+00:00")),
                    (date(2024, 3, 11), ("2024-03-11T10:00:00+00:00", "2024-03-11T13:00:00+00:00")))
        for day, pair in expected:
            self.assertEqual(tuple(map(utc, wall_interval(day, recipe("06:00", "09:00"), "America/New_York"))), pair)
        overnight = wall_interval(date(2024, 6, 3), recipe("20:00", "02:00", start_offset=-1), "America/New_York")
        self.assertEqual(tuple(map(utc, overnight)), ("2024-06-03T00:00:00+00:00", "2024-06-03T06:00:00+00:00"))
        fixed = wall_interval(date(2024, 3, 11), recipe("06:00", "09:00"), "Etc/GMT+5")
        self.assertEqual(tuple(map(utc, fixed)), ("2024-03-11T11:00:00+00:00", "2024-03-11T14:00:00+00:00"))
        for day, start, end in ((date(2024, 3, 10), "02:30", "03:30"),
                                (date(2024, 11, 3), "01:30", "02:30")):
            with self.subTest(day=day), self.assertRaises(ContractError):
                wall_interval(day, recipe(start, end), "America/New_York")
        calendar = CashCalendar(Path(__file__).resolve().parents[1] / "configs/cash-rth-calendar.json")
        day = date(2024, 11, 29)
        cut, _ = wall_interval(day, recipe("00:00", "00:01"), "America/New_York")
        cash = calendar.resolve(day, cut=cut)
        self.assertEqual(cash.state, "early_close")
        self.assertEqual((utc(cash.open_at), utc(cash.close_at)),
                         ("2024-11-29T14:30:00+00:00", "2024-11-29T18:00:00+00:00"))
        self.assertEqual(cash.scope, "cash_equity_rth_context")
        self.assertEqual(wall_interval(day, recipe("09:30", "13:00"), "America/New_York"),
                         (cash.open_at, cash.close_at))

