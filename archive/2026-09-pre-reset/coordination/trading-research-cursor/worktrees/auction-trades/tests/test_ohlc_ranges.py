M = 60_000_000_000
RAW = "NQM4"


def columns(rows):
    """Rows are (minute_index, OHLC[, known_at_ns, raw_contract, valid])."""
    result = {key: [] for key in (
        "start_ns", "end_ns", "known_at_ns", "open_ticks", "high_ticks",
        "low_ticks", "close_ticks", "volume", "contract_key", "valid")}
    for row in rows:
        minute, prices = row[:2]
        start, end = minute * M, (minute + 1) * M
        values = (start, end, row[2] if len(row) > 2 else end, *prices,
                  10, row[3] if len(row) > 3 else RAW, row[4] if len(row) > 4 else True)
        for key, value in zip(result, values, strict=True):
            result[key].append(value)
    return result


def series(rows):
    return MinuteBars(columns(rows), source_version="independent-observed-minute-fixture-v1")


def full_window(prices):
    return series(tuple((i, price) for i, price in enumerate(prices))).window(0, len(prices) * M,
                                                                            contract_key=RAW)


def utc(ns):
    return datetime.fromtimestamp(ns // 1_000_000_000, timezone.utc).isoformat()


def recipe(start, end, *, start_offset=0, end_offset=0):
    return {"start": {"day_offset": start_offset, "time": start},
            "end": {"day_offset": end_offset, "time": end}, "interval": "[start,end)"}


class OhlcRangeTests(unittest.TestCase):
    def test_jo01_half_open_and_delayed_final_publication(self):
        s = series(((0, (100, 104, 98, 102)),
                    (1, (102, 110, 101, 108), 122_000_000_000),
                    (2, (108, 999, 1, 500))))
        unavailable = s.window(0, 2 * M, contract_key=RAW, available_at=120_000_000_000)
        self.assertFalse(unavailable.complete)
        self.assertIn("final_bar_not_available", unavailable.reasons)
        with self.assertRaises(DependencyUnavailable):
            unavailable.geometry()
        window = s.window(0, 2 * M, contract_key=RAW, available_at=122_000_000_000)
        summary = window.summary()
        self.assertTrue(window.complete)
        self.assertEqual(window.count, 2)
        self.assertEqual(tuple(summary[k] for k in ("open_ticks", "high_ticks", "low_ticks", "close_ticks")),
                         (100, 110, 98, 108))
        self.assertEqual((summary["width_ticks"], summary["available_at_ns"]), (12, 122_000_000_000))
        prefix = series(((0, (100, 104, 98, 102)),
                         (1, (102, 110, 101, 108), 122_000_000_000)))
        self.assertEqual(summary, prefix.window(0, 2 * M, contract_key=RAW,
                                               available_at=122_000_000_000).summary())

