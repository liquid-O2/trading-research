    def test_later_definite_print_does_not_disappear_after_earlier_straddle(self):
        # The110 high can precede every actual100 print. The first definite
        # equality is the second bar's close, so it cannot raise a lower bound.
        result = level_outcome(full_window(((98, 110, 97, 101), (103, 104, 99, 100))),
                               level=Fraction(100), side=1)
        self.assertEqual((result["status"], result["conditional_on_contact"]), ("definite_level_print", False))
        self.assertEqual((result["contact_interval_start_ns"], result["contact_interval_end_ns"]), (0, M))
        self.assertEqual((result["first_definite_interval_start_ns"], result["first_definite_interval_end_ns"]),
                         (M, 2 * M))
        self.assertEqual((result["first_actual_contact_lower_ns"], result["first_actual_contact_upper_ns"]),
                         (0, 2 * M))
        self.assertEqual((result["favorable_lower_ticks"], result["favorable_upper_ticks"],
                          result["adverse_lower_ticks"], result["adverse_upper_ticks"]), (0, 10, 0, 3))
        later = level_outcome(full_window(((98, 110, 97, 101), (103, 104, 99, 100),
                                           (100, 106, 99, 104))), level=Fraction(100), side=1)
        self.assertEqual((later["favorable_lower_ticks"], later["favorable_upper_ticks"],
                          later["adverse_lower_ticks"], later["adverse_upper_ticks"]), (6, 10, 1, 3))
        possible_only = level_outcome(full_window(((98, 110, 97, 101), (103, 105, 99, 102))),
                                      level=Fraction(100), side=1)
        self.assertEqual((possible_only["status"], possible_only["conditional_on_contact"]),
                         ("compatible_straddle_only", True))
        self.assertEqual((possible_only["favorable_lower_ticks"], possible_only["favorable_upper_ticks"]),
                         (2, 10))

    def test_admitted_window_cannot_change_under_the_same_identity(self):
        original_columns = columns(((0, (100, 105, 99, 102)),))
        copied = MinuteBars(original_columns, source_version="immutable-fixture")
        original_columns["high_ticks"][0] = 999
        self.assertEqual(copied.window(0, M).geometry().high, 105)
        cached = copied.window(0, M, available_at=M)
        first_summary = cached.summary()
        original_version = first_summary["window_version"]
        first_summary["high_ticks"] = 999
        first_summary["exclusion_reasons"].append("caller_annotation")
        self.assertEqual(cached.summary()["high_ticks"], 105)
        self.assertEqual(cached.summary()["exclusion_reasons"], [])
        self.assertEqual(cached.summary()["window_version"], original_version)
        self.assertEqual(cached.geometry().high, 105)
        unavailable = copied.window(0, M, available_at=M - 1)
        self.assertNotEqual(unavailable.version, original_version)
        changed = unavailable.summary()
        changed["exclusion_reasons"].clear()
        self.assertIn("final_bar_not_available", unavailable.summary()["exclusion_reasons"])
        with self.assertRaises(DependencyUnavailable):
            unavailable.geometry()
        with self.assertRaises((AttributeError, TypeError, ContractError)):
            copied.source_version = "changed-source-claim"
        for field, replacement in (("high", 999), ("known", 10 * M)):
            s = series(((0, (100, 105, 99, 102)),))
            window = s.window(0, M, available_at=M)
            original_version = window.version
            try:
                getattr(s, field)[0] = replacement
            except (TypeError, AttributeError, ContractError):
                self.assertEqual(window.version, original_version)
                self.assertEqual(window.summary()["high_ticks"], 105)
                self.assertEqual(window.summary()["available_at_ns"], M)
            else:
                with self.assertRaises(IntegrityError):
                    window.summary()

